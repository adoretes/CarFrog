import type { CharaCard } from '../types'
import { cardToJsonString } from './charaUtils'

export function downloadJson(card: CharaCard, filename?: string) {
  const json = cardToJsonString(card)
  const blob = new Blob([json], { type: 'application/json' })
  downloadBlob(blob, filename || `${card.data.name || '角色卡'}.json`)
}

export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  a.click()
  URL.revokeObjectURL(url)
}

export function readFileAsText(file: File): Promise<string> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader()
    reader.onload = () => resolve(reader.result as string)
    reader.onerror = reject
    reader.readAsText(file)
  })
}

